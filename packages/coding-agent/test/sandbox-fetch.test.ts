	test("real TLS response keeps original Host/SNI and rejects a mismatched certificate identity", async () => {
		await fixture();
		const seen: Array<{ host: string | undefined; servername: string | false | undefined }> = [];
		const sockets = new Set<Socket>();
		const server = https.createServer({ key: sandboxTlsKey, cert: sandboxTlsCert }, (request, response) => {
			seen.push({ host: request.headers.host, servername: "servername" in request.socket ? request.socket.servername as string : undefined });
			response.writeHead(418, { "x-tls-fixture": "actual response" });
			response.end("real encrypted fixture response 雪");
		});
		server.on("connection", socket => { sockets.add(socket); socket.once("close", () => sockets.delete(socket)); });
		const ready = Promise.withResolvers<void>();
		server.once("error", ready.reject); server.listen(0, "127.0.0.1", ready.resolve); await ready.promise;
		const bound = server.address();
		if (!bound || typeof bound === "string") throw new Error("TLS fixture did not bind a TCP port");
		const port = bound.port;
		fixtures.push({ async close() {
			for (const socket of sockets) socket.destroy();
			const stopped = Promise.withResolvers<void>();
			server.close(error => error ? stopped.reject(error) : stopped.resolve()); await stopped.promise;
		} });
		const original = https.Agent.prototype.createConnection;
		const connector = spyOn(https.Agent.prototype, "createConnection").mockImplementation(function (this: https.Agent, options, callback) {
			expect(options.rejectUnauthorized).toBe(true);
			let approved: string | undefined;
			options.lookup!(String(options.host), { family: Number(options.family) }, (error, address) => {
				if (error || typeof address !== "string") throw new Error("TLS fixture did not receive a pinned address");
				approved = address;
			});
			expect(approved).toBe("93.184.216.34");
			// Only this test seam trusts the fixed test certificate; production trust settings stay intact.
			return original.call(this, { ...options, host: "127.0.0.1", hostname: "127.0.0.1", port, family: 4, lookup: undefined, ca: sandboxTlsCert }, callback);
		});
		restores.push(connector);
		const result = await sandboxFetch({ url: `https://public.omp.sh:${port}/real` });
		expect(result).toMatchObject({ status: 418, body: "real encrypted fixture response 雪" });
		expect(result.headers["x-tls-fixture"]).toBe("actual response");
		expect(seen).toEqual([{ host: `public.omp.sh:${port}`, servername: "public.omp.sh" }]);
		const failedSocketClosed = Promise.withResolvers<void>();
		server.once("connection", socket => socket.once("close", failedSocketClosed.resolve));
		const failure = await sandboxFetch({ url: `https://other.omp.sh:${port}/wrong` }).catch(error => error);
		expect(failure).toBeInstanceOf(Error);
		expect(failure.constructor.name).toBe("SandboxFetchError");
		expect(failure.cause).toBeInstanceOf(Error);
		expect(failure.message).not.toContain("/private/");
		await failedSocketClosed.promise;
		expect(sockets.size).toBe(0);
		const resultError = await sandboxFetchTool().execute("tls-mismatch", { url: `https://other.omp.sh:${port}/wrong` }, undefined, undefined, {} as ExtensionContext);
		expect(resultError.isError).toBe(true);
		expect(seen).toHaveLength(1);
	});

